/**
 * Developer-run generator for the premium avatar catalog (Main Stage + Hall of
 * Fame). This file is the ONLY place the per-avatar rarity bands, prices and
 * rating gates are edited; it writes both mirrors so they cannot drift:
 *
 *   server/src/avatarCatalog.generated.ts   -- authoritative (equip/purchase/seed)
 *   src/constants/avatarImages.generated.ts -- client mirror + static require()s
 *
 * Metro needs literal require() paths, so the client file is generated rather
 * than built dynamically (same reason as src/components/ui/pieceSprites.ts).
 * Garage Band (the 12 original free badges) is NOT generated -- it is
 * hand-written in src/constants/avatars.ts / server/src/avatars.ts.
 *
 * Usage (from repo root):  node scripts/gen-avatar-catalog.mjs
 * Re-run after editing BANDS or the id lists below, then commit the outputs.
 */
import { existsSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = process.cwd();

// gems : chips is held at 1:20 like boards/pieces (Hall of Fame has no chip
// price at all -- gems only).
const BANDS = {
  main_stage: {
    common: { gemPrice: 100, chipPrice: 2_000, minRating: null },
    rare: { gemPrice: 200, chipPrice: 4_000, minRating: null },
    legendary: { gemPrice: 300, chipPrice: 6_000, minRating: null },
  },
  // Rating gates reuse src/lib/tierLabel.ts's thresholds (1400 / 1800 / 2200).
  hall_of_fame: {
    gold: { gemPrice: 600, chipPrice: null, minRating: 1400 },
    platinum: { gemPrice: 900, chipPrice: null, minRating: 1800 },
    immortal: { gemPrice: 1200, chipPrice: null, minRating: 2200 },
  },
};

// rarity -> ids (the file name without .png). Bands were assigned by hand.
const MAIN_STAGE = {
  legendary: ['dark-majesty', 'silver-fox-frontman', 'hellfire-skull', 'cyber-reaper', 'thorn-queen', 'warlord-beard', 'crimson-riff'],
  rare: ['chrome-skull', 'velvet-widow', 'spiked-duchess', 'silver-phantom', 'violet-specter', 'teal-banshee', 'shred-siren', 'grave-mane', 'glam-star', 'hooded-tactician', 'thunder-drummer', 'toxic-bassist', 'iron-mane', 'chain-ghoul'],
  common: ['backbeat-brat', 'bass-braids', 'blue-spike', 'cobalt-cowl', 'crypt-crooner', 'cyber-shades', 'drum-fury', 'dusty-outlaw', 'ember-dreads', 'faded-legend', 'glitch-punk', 'grizzly-biker', 'neon-visor', 'pink-scream', 'road-dog', 'screamer', 'spike-havoc', 'steel-stubble', 'synth-rebel', 'violet-riot'],
};
const HALL_OF_FAME = {
  immortal: ['skeleton-king', 'golden-mane-king', 'neon-werewolf', 'midnight-raven', 'platinum-siren', 'shadow-cloak'],
  platinum: ['lightning-scar', 'top-hat-maverick', 'chrome-visor', 'ice-punk', 'violet-shredder', 'scarlet-scarf', 'wildfire-curls', 'aviator-frontman'],
  gold: ['afro-mixmaster', 'bandana-legend', 'chain-gang', 'cobalt-mohawk', 'crimson-bandana', 'lavender-keys', 'neon-beats', 'pulse-dj', 'scarlet-bass', 'stickman-storm'],
};

const FOLDERS = { main_stage: 'main-stage', hall_of_fame: 'hall-of-fame' };
// Existing Garage Band ids + board/piece ids: a new id must never collide
// (cosmetic_items.id is one global primary key across categories).
const RESERVED = new Set([
  'axe', 'nova', 'riff', 'axl', 'blaze', 'beats', 'mic-drop', 'synth', 'reaper', 'king', 'rebel', 'legend',
  'classic-chrome', 'cyan-storm', 'gold-rush', 'crimson-stage', 'obsidian-void',
  'classic-pieces', 'graphite-tour', 'molten-gold', 'crimson-reaper',
]);

const titleCase = (id) => id.split('-').map((w) => w[0].toUpperCase() + w.slice(1)).join(' ');

const entries = [];
const seen = new Set();
for (const [klass, groups] of [['main_stage', MAIN_STAGE], ['hall_of_fame', HALL_OF_FAME]]) {
  for (const [rarity, ids] of Object.entries(groups)) {
    for (const id of ids) {
      if (seen.has(id) || RESERVED.has(id)) throw new Error(`duplicate/reserved avatar id: ${id}`);
      seen.add(id);
      const file = join(ROOT, 'assets', 'avatar', FOLDERS[klass], `${id}.png`);
      if (!existsSync(file)) throw new Error(`missing asset: ${file}`);
      entries.push({ id, name: titleCase(id), class: klass, rarity, folder: FOLDERS[klass], ...BANDS[klass][rarity] });
    }
  }
}
if (entries.filter((e) => e.class === 'main_stage').length !== 41) throw new Error('expected 41 Main Stage avatars');
if (entries.filter((e) => e.class === 'hall_of_fame').length !== 24) throw new Error('expected 24 Hall of Fame avatars');

const order = { main_stage: 0, hall_of_fame: 1 };
const rank = { common: 0, rare: 1, legendary: 2, gold: 0, platinum: 1, immortal: 2 };
entries.sort((a, b) => order[a.class] - order[b.class] || rank[a.rarity] - rank[b.rarity] || a.id.localeCompare(b.id));

const banner = '// GENERATED by scripts/gen-avatar-catalog.mjs -- do not edit by hand.\n';
const data = (e, withImage) =>
  `  { id: '${e.id}', name: '${e.name}', class: '${e.class}', rarity: '${e.rarity}', gemPrice: ${e.gemPrice}, chipPrice: ${e.chipPrice}, minRating: ${e.minRating}${
    withImage ? `, image: require('../../assets/avatar/${e.folder}/${e.id}.png')` : ''
  } },`;

writeFileSync(
  join(ROOT, 'server', 'src', 'avatarCatalog.generated.ts'),
  `${banner}// Authoritative premium-avatar catalog (prices, rarity, rating gates).\n` +
    `export type PremiumAvatarClass = 'main_stage' | 'hall_of_fame';\n` +
    `export type AvatarRarity = 'common' | 'rare' | 'legendary' | 'gold' | 'platinum' | 'immortal';\n\n` +
    `export interface PremiumAvatarEntry {\n  id: string;\n  name: string;\n  class: PremiumAvatarClass;\n  rarity: AvatarRarity;\n  gemPrice: number;\n  chipPrice: number | null; // null = gems only\n  minRating: number | null; // null = no rating gate\n}\n\n` +
    `export const PREMIUM_AVATARS: PremiumAvatarEntry[] = [\n${entries.map((e) => data(e, false)).join('\n')}\n];\n`,
);

writeFileSync(
  join(ROOT, 'src', 'constants', 'avatarImages.generated.ts'),
  `${banner}import type { ImageSourcePropType } from 'react-native';\n\n` +
    `import type { AvatarClass, AvatarRarity } from './avatars';\n\n` +
    `// Client mirror of server/src/avatarCatalog.generated.ts plus the static\n// require()s Metro needs.\n` +
    `export interface PremiumAvatarAsset {\n  id: string;\n  name: string;\n  class: Exclude<AvatarClass, 'garage_band'>;\n  rarity: AvatarRarity;\n  gemPrice: number;\n  chipPrice: number | null;\n  minRating: number | null;\n  image: ImageSourcePropType;\n}\n\n` +
    `export const PREMIUM_AVATAR_ASSETS: PremiumAvatarAsset[] = [\n${entries.map((e) => data(e, true)).join('\n')}\n];\n`,
);

console.log(`Wrote ${entries.length} premium avatars.`);
