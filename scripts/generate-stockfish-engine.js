/**
 * Base64-embeds the Stockfish lite single-threaded WASM build into a TS
 * module the app can bundle offline, no expo-file-system/asset plumbing.
 *
 *   node scripts/generate-stockfish-engine.js
 *
 * Reads node_modules/stockfish/bin/stockfish-18-lite-single.{js,wasm} and
 * writes src/lib/stockfishEngineAssets.ts (gitignored -- regenerate after
 * `npm install`, same as any other node_modules-derived build output).
 *
 * Why base64-embed instead of loading the files from disk at runtime: this
 * repo has no existing pattern for shipping/loading static assets into a
 * WebView (no expo-file-system dependency, no metro asset-ext wiring for
 * .wasm), and StockfishEngine.tsx needs the engine reachable fully offline
 * from an inline `source={{ html }}` WebView with no real origin for a
 * relative fetch to resolve against. Embedding sidesteps both problems at
 * the cost of ~9-10MB of generated source text.
 */

const fs = require('fs');
const path = require('path');

const VENDOR_DIR = path.join(__dirname, '..', 'node_modules', 'stockfish', 'bin');
const JS_PATH = path.join(VENDOR_DIR, 'stockfish-18-lite-single.js');
const WASM_PATH = path.join(VENDOR_DIR, 'stockfish-18-lite-single.wasm');
const OUT_PATH = path.join(__dirname, '..', 'src', 'lib', 'stockfishEngineAssets.ts');

function main() {
  if (!fs.existsSync(JS_PATH) || !fs.existsSync(WASM_PATH)) {
    console.error('Stockfish vendor files not found -- run `npm install` first.');
    console.error('Expected:', JS_PATH, 'and', WASM_PATH);
    process.exit(1);
  }

  const jsSource = fs.readFileSync(JS_PATH, 'utf8');
  const wasmBase64 = fs.readFileSync(WASM_PATH).toString('base64');

  console.log('JS glue:', jsSource.length, 'chars');
  console.log('WASM binary:', WASM_PATH, '->', wasmBase64.length, 'base64 chars');

  const out = `/**
 * GENERATED by scripts/generate-stockfish-engine.js -- do not edit by hand.
 * Run: node scripts/generate-stockfish-engine.js
 *
 * Source: node_modules/stockfish@18.0.8 (stockfish-18-lite-single.{js,wasm}).
 */
export const STOCKFISH_JS_SOURCE = ${JSON.stringify(jsSource)};
export const STOCKFISH_WASM_BASE64 = ${JSON.stringify(wasmBase64)};
`;

  fs.writeFileSync(OUT_PATH, out);
  console.log('Wrote', OUT_PATH, `(${(out.length / 1024 / 1024).toFixed(1)}MB)`);
}

main();
